/// emits the literal swizzle text as-is.
/// Write swizzles are deliberately not supported - reconstruct instead
/// (`color = new Vector4(x, color.Y, color.Z, color.W)`).
/// Generated by scripts/gen_swizzles.py - do not hand-edit, regenerate instead.
/// </summary>
