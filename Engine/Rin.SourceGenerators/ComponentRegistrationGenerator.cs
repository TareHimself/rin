using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Threading;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Rin.SourceGenerators;

[Generator]
public class ComponentRegistrationGenerator : IIncrementalGenerator
{
    private const string ComponentInterface = "Rin.World.IComponentData";
    private const string TagInterface = "Rin.World.ITagData";
    private const string Registry = "global::Rin.World.ComponentRegistry";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var candidates = context.SyntaxProvider
            .CreateSyntaxProvider(
                predicate: static (node, _) => IsStructWithBaseList(node),
                transform: static (ctx, ct) => GetCandidate(ctx, ct))
            .Where(static candidate => candidate is not null)
            .Select(static (candidate, _) => candidate!.Value);

        context.RegisterSourceOutput(candidates.Collect(), static (spc, items) => Execute(spc, items));
    }

    private static bool IsStructWithBaseList(SyntaxNode node) => node switch
    {
        StructDeclarationSyntax { BaseList: not null } => true,
        RecordDeclarationSyntax { BaseList: not null } record => record.ClassOrStructKeyword.IsKind(SyntaxKind.StructKeyword),
        _ => false
    };

    private static ComponentCandidate? GetCandidate(GeneratorSyntaxContext context, CancellationToken cancellationToken)
    {
        if (context.SemanticModel.GetDeclaredSymbol(context.Node, cancellationToken) is not INamedTypeSymbol type)
            return null;

        var kind = KindOf(type);
        if (kind is null) return null;

        var name = type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        var location = ((TypeDeclarationSyntax)context.Node).Identifier.GetLocation();
        return new ComponentCandidate(name, kind.Value, ProblemOf(type), location);
    }

    private static ComponentKind? KindOf(INamedTypeSymbol type)
    {
        foreach (var implemented in type.AllInterfaces)
        {
            var name = implemented.ToDisplayString();
            if (name == ComponentInterface) return ComponentKind.Component;
            if (name == TagInterface) return ComponentKind.Tag;
        }

        return null;
    }

    private static string? ProblemOf(INamedTypeSymbol type)
    {
        if (type.IsRefLikeType) return "it is a ref struct";

        for (var current = type; current is not null; current = current.ContainingType)
        {
            if (current.IsGenericType)
                return "it is generic, so register each closed type with ComponentRegistry by hand";
            if (current.IsFileLocal) return $"'{current.Name}' is file-local";
            if (current.DeclaredAccessibility is Accessibility.Private or Accessibility.Protected
                or Accessibility.ProtectedAndInternal)
                return $"'{current.Name}' is private or protected, make it internal or public";
        }

        return null;
    }

    private static void Execute(SourceProductionContext context, ImmutableArray<ComponentCandidate> candidates)
    {
        var registrable = new SortedDictionary<string, ComponentKind>(System.StringComparer.Ordinal);
        var reported = new HashSet<string>();

        foreach (var candidate in candidates)
        {
            if (candidate.Problem is null)
            {
                registrable[candidate.Name] = candidate.Kind;
                continue;
            }

            if (reported.Add(candidate.Name))
                context.ReportDiagnostic(Diagnostic.Create(Diagnostics.Ecs.CannotRegisterComponent,
                    candidate.Location, candidate.Name, candidate.Problem));
        }

        if (registrable.Count == 0) return;

        var output = new SourceBuilder()
            .Line("// <auto-generated/>")
            .Line()
            .Line("namespace Rin.Generated;")
            .Line()
            .Line("internal static class ComponentRegistration")
            .OpenBrace()
            .Line("[global::System.Runtime.CompilerServices.ModuleInitializer]")
            .Line("internal static void Register()")
            .OpenBrace();

        foreach (var pair in registrable)
        {
            var method = pair.Value == ComponentKind.Component ? "RegisterComponent" : "RegisterTag";
            output.Line($"{Registry}.{method}<{pair.Key}>();");
        }

        output.CloseBrace().CloseBrace();

        context.AddSource("ComponentRegistration.g.cs", output.ToSourceText());
    }

    private enum ComponentKind
    {
        Component,
        Tag
    }

    private readonly struct ComponentCandidate(string name, ComponentKind kind, string? problem, Location location)
    {
        public string Name { get; } = name;
        public ComponentKind Kind { get; } = kind;
        public string? Problem { get; } = problem;
        public Location Location { get; } = location;
    }
}
